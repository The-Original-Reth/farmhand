"""
Parser for PrusaSlicer and PrusaSlicer BOSS edition 3MF files.

Per spec, BOSS edition does not change the 3MF output format versus vanilla
PrusaSlicer — it only exposes more variables in the slicer UI — so both are
handled by this single parser.

The config is stored as a flat list of `; key = value` lines inside
Metadata/Slic3r_PE.config. This parser turns that into a plain dict and
pulls out the handful of fields the rest of the app cares about directly
(which printer profile this was sliced for, the slicer version string).
Every other key is kept as-is in `settings` — per spec, unknown/unmapped
fields still get stored and displayed, never dropped.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from .threemf import RawThreeMF

_LINE_RE = re.compile(r"^;\s*([a-zA-Z0-9_]+)\s*=\s*(.*)$")
_HEADER_VERSION_RE = re.compile(r"generated by PrusaSlicer\s+(\S+)", re.IGNORECASE)


@dataclass
class ParsedBundle:
    slicer_family: str
    slicer_display_name: str  # e.g. "PrusaSlicer 2.9.5-rc1"
    printer_profile_name: str | None  # physical_printer_settings_id
    print_settings_id: str | None
    filament_settings_id: str | None
    settings: dict = field(default_factory=dict)
    thumbnail_bytes: bytes | None = None
    printer_preset_name: str | None = None  # printer_settings_id: the preset under the physical printer (a sub printer)


def parse(raw: RawThreeMF) -> ParsedBundle:
    if not raw.config_text:
        raise ValueError("No Slic3r_PE.config found in this 3MF — cannot parse as PrusaSlicer output")

    settings: dict[str, str] = {}
    for line in raw.config_text.splitlines():
        m = _LINE_RE.match(line)
        if m:
            key, value = m.group(1), m.group(2)
            settings[key] = value

    version_match = _HEADER_VERSION_RE.search(raw.config_text)
    version = version_match.group(1) if version_match else "unknown version"

    return ParsedBundle(
        slicer_family="prusaslicer",
        slicer_display_name=f"PrusaSlicer {version}",
        printer_profile_name=settings.get("physical_printer_settings_id") or None,
        print_settings_id=settings.get("print_settings_id") or None,
        filament_settings_id=settings.get("filament_settings_id") or None,
        settings=settings,
        thumbnail_bytes=raw.thumbnail_bytes,
        printer_preset_name=settings.get("printer_settings_id") or None,
    )
