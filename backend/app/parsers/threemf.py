"""
Low-level .3mf (zip) access shared by every slicer-specific parser.

A .3mf file is a standard zip archive. Different slicers put their config
dump in different places inside it:
  - PrusaSlicer / PrusaSlicer BOSS: Metadata/Slic3r_PE.config
  - OrcaSlicer:                     Metadata/Slic3r_PE.config as well in
                                     most builds, but with different key
                                     names/coverage — handled by its own
                                     parser (see orcaslicer.py, stubbed).

This module only knows how to open the zip and pull out well-known member
paths. It has no opinion about what the config file's contents mean.
"""
from __future__ import annotations

import zipfile
from dataclasses import dataclass

THUMBNAIL_CANDIDATES = [
    "Metadata/thumbnail.png",
    "Metadata/thumbnail_small.png",
    "Metadata/plate_1.png",  # OrcaSlicer sometimes names it this way
]

CONFIG_CANDIDATES = [
    "Metadata/Slic3r_PE.config",
]


@dataclass
class RawThreeMF:
    """Everything pulled out of the zip before any slicer-specific parsing."""

    config_text: str | None
    config_member: str | None
    thumbnail_bytes: bytes | None
    thumbnail_member: str | None
    all_members: list[str]


def read_3mf(path: str) -> RawThreeMF:
    with zipfile.ZipFile(path, "r") as zf:
        members = zf.namelist()

        config_text = None
        config_member = None
        for candidate in CONFIG_CANDIDATES:
            if candidate in members:
                config_member = candidate
                config_text = zf.read(candidate).decode("utf-8", errors="replace")
                break

        thumbnail_bytes = None
        thumbnail_member = None
        for candidate in THUMBNAIL_CANDIDATES:
            if candidate in members:
                thumbnail_member = candidate
                thumbnail_bytes = zf.read(candidate)
                break

        return RawThreeMF(
            config_text=config_text,
            config_member=config_member,
            thumbnail_bytes=thumbnail_bytes,
            thumbnail_member=thumbnail_member,
            all_members=members,
        )


def detect_slicer_family(raw: RawThreeMF) -> str:
    """
    Best-effort detection of which parser should handle this file.

    PrusaSlicer and PrusaSlicer BOSS share an output format (per spec: BOSS
    just exposes more variables, doesn't change the format), so both are
    handled by the 'prusaslicer' family. OrcaSlicer is detected by looking
    at the config's own declared app name where present.
    """
    if not raw.config_text:
        return "unknown"
    first_lines = raw.config_text.splitlines()[:5]
    header = " ".join(first_lines).lower()
    if "orcaslicer" in header:
        return "orcaslicer"
    # PrusaSlicer's config header line looks like:
    #   ; generated by PrusaSlicer 2.9.5-rc1 on ...
    if "prusaslicer" in header or "slic3r" in header:
        return "prusaslicer"
    # Fall back to the only parser we've actually implemented against real
    # files so far. Revisit once OrcaSlicer sample files are available.
    return "prusaslicer"
