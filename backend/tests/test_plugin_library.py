def test_a_gcode_is_sent_to_the_printer_the_farmhand_way(api, farm, monkeypatch):
    auth = install(api)
    sent = {}

    def send_file(db, printer, name, path):
        with open(path, "rb") as f:
            sent.update(printer=printer.name, name=name, data=f.read())
        return {"sent": f"{printer.name}:/{name}", "printer": printer.name}

    monkeypatch.setattr(send_print, "send_file", send_file)
    r = api.post(f"/plugin-api/v1/printers/{farm['core']}/print", headers=auth, files={"gcode": ("Frog.gcode", b"G28\nG1 X1\n")})
    assert r.status_code == 200, r.text
    assert r.json() == {"sent": "Core One:/Frog.gcode", "printer": "Core One"}
    assert sent == {"printer": "Core One", "name": "Frog.gcode", "data": b"G28\nG1 X1\n"}


def test_a_busy_printer_or_a_file_that_isnt_gcode_is_refused(api, farm, monkeypatch):
    auth = install(api)

    def busy(db, printer, name, path):
        raise send_print.PrinterBusy(f"{printer.name} is printing, so a new print can't be started.")

    monkeypatch.setattr(send_print, "send_file", busy)
    r = api.post(f"/plugin-api/v1/printers/{farm['core']}/print", headers=auth, files={"gcode": ("Frog.gcode", b"G28\n")})
    assert r.status_code == 409 and "is printing" in r.json()["detail"]
    r = api.post(f"/plugin-api/v1/printers/{farm['core']}/print", headers=auth, files={"gcode": ("Frog.stl", b"solid")})
    assert r.status_code == 422 and ".gcode or .bgcode" in r.json()["detail"]
    assert api.post("/plugin-api/v1/printers/999/print", headers=auth, files={"gcode": ("a.gcode", b"G28")}).status_code == 404
