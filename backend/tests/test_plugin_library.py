def plan(api, auth, refs, printer, **extra):
    return api.get("/plugin-api/v1/library/sliced/plan", params={"ref": refs, "printer_id": printer, **extra}, headers=auth)


def test_where_a_sliced_3mf_goes(api, farm):
    auth = install(api)
    one = plan(api, auth, [f"model:{farm['frog']}"], farm["core"]).json()
    assert one["action"] == "new_3mf" and one["name"] == "Frog" and one["says"] == "Saved as a new 3MF, Frog, on Core One."
    again = plan(api, auth, [f"3mf:{farm['frog_3mf']}"], farm["core"]).json()
    assert again["action"] == "new_version" and again["name"] == "Frog" and again["bundle_id"] == farm["bundle"]
    elsewhere = plan(api, auth, [f"3mf:{farm['frog_3mf']}"], farm["mini"]).json()
    assert elsewhere["action"] == "new_3mf" and elsewhere["model_ids"] == [farm["frog"]]
    both = plan(api, auth, [f"model:{farm['frog']}", f"model:{farm['shark']}"], farm["core"]).json()
    assert both["action"] == "new_3mf_and_project" and both["name"] == both["project_name"] == "Frog + Shark"
    named = plan(api, auth, [f"model:{farm['frog']}", f"model:{farm['shark']}"], farm["core"], project_name="Aquarium").json()
    assert named["project_name"] == "Aquarium" and named["name"] == "Aquarium"
    hull = plan(api, auth, [f"project-stl:{farm['project']}:{farm['hull']}", f"model:{farm['frog']}"], farm["core"]).json()
    assert hull["action"] == "project_3mf" and hull["project_id"] == farm["project"] and hull["name"] == "Boat"


def test_a_3mf_from_two_projects_or_with_a_taken_project_name_is_refused(api, farm):
    auth = install(api)
    other = api.post("/projects", json={"name": "Raft"}).json()["id"]
    r = api.post(f"/projects/{other}/stl", files={"file": ("Log.stl", io.BytesIO(make.stl_bytes()))}, data={"in_models": "false"})
    log = r.json()["stl_files"][0]["id"]
    r = plan(api, auth, [f"project-stl:{farm['project']}:{farm['hull']}", f"project-stl:{other}:{log}"], farm["core"])
    assert r.status_code == 422 and "different projects (Boat, Raft)" in r.json()["detail"]
    r = plan(api, auth, [f"model:{farm['frog']}", f"model:{farm['shark']}"], farm["core"], project_name="boat")
    assert r.status_code == 422 and "already a project called Boat" in r.json()["detail"]
    assert plan(api, auth, [f"model:{farm['frog']}"], 999).status_code == 404


def save(api, auth, refs, printer, gcode=b"G28\n", **extra):
    files = {"threemf": ("project.3mf", threemf())}
    if gcode is not None:
        files["gcode"] = ("output.gcode", gcode)
    return api.post("/plugin-api/v1/library/sliced", headers=auth, files=files,
                    data={"refs": json.dumps(refs), "printer_id": str(printer), **extra})


def test_a_3mf_sliced_from_one_model_is_a_new_3mf_named_after_it(api, farm):
    auth = install(api)
    r = save(api, auth, [f"model:{farm['shark']}"], farm["core"])
    assert r.status_code == 201, r.text
    out = r.json()
    assert out["action"] == "new_3mf" and out["filename"] == "Shark ver 1.3mf" and out["version"] == 1
    version = api.get(f"/bundles/versions/{out['version_id']}").json()
    assert version["gcode_name"] == "Shark ver 1.gcode"
    bundles = api.get(f"/source-models/{farm['shark']}/bundles").json()
    assert [b["id"] for b in bundles] == [out["bundle_id"]]


def test_a_3mf_resliced_for_its_printer_is_its_next_version(api, farm):
    auth = install(api)
    out = save(api, auth, [f"3mf:{farm['frog_3mf']}"], farm["core"], gcode=None).json()
    assert out["action"] == "new_version" and out["bundle_id"] == farm["bundle"]
    assert out["version"] == 2 and out["filename"] == "Frog ver 2.3mf"


def test_a_3mf_from_several_models_makes_a_project_with_them(api, farm):
    auth = install(api)
    out = save(api, auth, [f"model:{farm['frog']}", f"model:{farm['shark']}"], farm["core"], project_name="Aquarium").json()
    assert out["action"] == "new_3mf_and_project" and out["filename"] == "Aquarium ver 1.3mf"
    db = api_db(api)
    bundle = db.get(Bundle, out["bundle_id"])
    assert sorted(m.id for m in bundle.source_models) == sorted([farm["frog"], farm["shark"]])
    project = api.get(f"/projects/{out['project_id']}").json()
    assert project["name"] == "Aquarium" and sorted(project["source_model_ids"]) == sorted([farm["frog"], farm["shark"]])
    assert project["bundle_ids"] == [out["bundle_id"]] and project["printer_ids"] == [farm["core"]]


def test_a_3mf_from_a_projects_own_files_stays_in_the_project(api, farm):
    auth = install(api)
    out = save(api, auth, [f"project-stl:{farm['project']}:{farm['hull']}"], farm["core"]).json()
    assert out["action"] == "project_3mf" and out["filename"] == "Hull ver 1.3mf"
