def test_the_files_sent_are_described_by_their_refs(api, farm):
    auth = install(api)
    refs = [f"model:{farm['frog']}", f"3mf:{farm['frog_3mf']}", f"project-stl:{farm['project']}:{farm['hull']}"]
    r = api.get("/plugin-api/v1/library/files", params={"ref": refs}, headers=auth)
    assert r.status_code == 200, r.text
    model, sliced, hull = r.json()["files"]
    assert model == {**model, "ref": refs[0], "kind": "stl", "name": "Frog.stl", "available": True, "sliceable": True,
                     "model_ids": [farm["frog"]], "printer_id": None}
    assert sliced == {**sliced, "kind": "3mf", "name": "Frog ver 1.3mf", "printer_id": farm["core"],
                      "bundle_id": farm["bundle"], "model_ids": [farm["frog"]]}
    assert hull == {**hull, "kind": "stl", "name": "Hull ver 1.stl", "project_id": farm["project"], "project_name": "Boat"}


