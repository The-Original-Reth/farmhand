# ------------------------------------------------------------------ the manifest


def test_a_slicer_manifest_asks_for_the_new_permissions_and_says_what_it_takes():
    checked = manifest.check(SLICER)
    assert checked["send_files"] == {"label": "Slicer", "path": "/open", "kinds": ["stl", "3mf"]}
    assert manifest.check({**SLICER, "send_files": {"label": "Slicer"}})["send_files"]["kinds"] == ["stl", "obj", "3mf"]
    assert {"library:read", "library:write", "prints:send"} <= set(manifest.PERMISSIONS)


@pytest.mark.parametrize("change, words", [
    ({"send_files": "Slicer"}, "send_files must be an object"),
    ({"send_files": {"path": "/open"}}, "send_files label must be text"),
    ({"send_files": {"label": "Slicer", "kinds": ["step"]}}, "kinds must be a list of stl, obj, 3mf"),
    ({"send_files": {"label": "Slicer", "path": "open"}}, "send_files path must be a path"),
    ({"permissions": ["printers:read"]}, "must ask for library:read"),
    ({"page": None}, "needs a page"),
])
def test_a_bad_send_files_says_what_is_wrong(change, words):
    with pytest.raises(ValueError) as e:
        manifest.check({**SLICER, **change})
    assert words in str(e.value)


