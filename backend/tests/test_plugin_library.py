def install(api, permissions=None) -> dict:
    r = api.post("/plugins", json={"manifest": SLICER, "permissions": permissions or SLICER["permissions"]})
    assert r.status_code == 201, r.text
    return {"Authorization": f"Bearer {r.json()['token']}"}


def threemf(preset="Original Prusa MK4S 0.4 nozzle") -> bytes:
    """A 3MF as a slicer writes it: its settings (and so its printer preset) inside"""
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        z.writestr("3D/3dmodel.model", "<model/>")
        z.writestr("Metadata/Slic3r_PE.config",
                   f"; generated by PrusaSlicer 2.9.0 on 2026-11-13\n; printer_settings_id = {preset}\n"
                   "; physical_printer_settings_id = \n; fill_density = 15%\n")
    return out.getvalue()


